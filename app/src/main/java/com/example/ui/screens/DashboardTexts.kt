package com.example.ui.screens

object DashboardTexts {

    fun getGreeting(hour: Int, minute: Int = 0): String {
        return when (hour) {
            in 5..11 -> "صبح بخیر برسام جان ☀️"
            in 12..16 -> "ظهر بخیر برسام جان 🌤️"
            in 17..19 -> "عصر بخیر برسام جان 🌇"
            else -> "شب بخیر برسام جان 🌙"
        }
    }

    fun getWeekdayMessage(weekdayName: String): String {
        return when (weekdayName) {
            "شنبه" -> "شروع هفته است؛ یک سؤال سخت را امروز شکست بده! 💪"
            "یکشنبه" -> "پشتکار از استعداد مهم\u200Cتر است؛ امروز هم یک قدم جلوتر برو. 🚶"
            "دوشنبه" -> "اشتباه\u200Cها معلم\u200Cهای خوبی\u200Cاند؛ امروز از یکی\u200Cشان یاد بگیر. 📘"
            com.example.util.JalaliCalendarUtils.WEEKDAY_TUESDAY -> "وسط هفته\u200Cای؛ نفس بگیر و با تمرکز ادامه بده. 🎯"
            "چهارشنبه" -> "یک آزمون کوتاه امتحان کن و خودت را بسنج. 📝"
            "پنجشنبه" -> "مرور کن؛ چیزی که دوباره دیده شود، ماندگار می\u200Cشود. 🔁"
            "جمعه" -> "امروز استراحت هم بخشی از پیشرفت است؛ کمی تفریح کن. 🌿"
            else -> "با انرژی و تمرکز بالا ادامه بده! 🚀"
        }
    }

    val SLOGANS = listOf(
        "ریاضی زبان درک شگفتی‌های جهان است.",
        "هر مسئله دشوار، فرصتی برای درخشش ذهن توست.",
        "لذت حل مسئله، پاداش شیرین صبر و تمرکز است.",
        "فرمول‌ها پرواز فکر را ممکن می‌سازند؛ اوج بگیر!",
        "پشت هر معما، کشفی زیبا در انتظار تو نشسته است.",
        "ریاضیات نه فقط حساب و کتاب، که هنر اندیشیدن است.",
        "گام‌های کوچک اما پیوسته، تو را به اوج قله کنکور می‌رساند.",
        "اشتباه امروزت، پل پیروزی فردای تو در کنکور است.",
        "شجاعت مواجهه با مسائل سخت، تفکر یک رتبه برتر را می‌سازد.",
        "هندسه و حساب، بال‌های پرواز در آسمان دانایی‌اند."
    )

    fun getSloganOfTheDay(year: Int, month: Int, day: Int): String {
        val hash = (year * 365 + month * 31 + day)
        val index = ((hash % SLOGANS.size) + SLOGANS.size) % SLOGANS.size
        return SLOGANS[index]
    }
}
